class GraphState(TypedDict):    #状态管理类，每次迭代都要使用到其中的变量
    category_index: int
    title_index: int
    prompt_num: int
    improvement: str
    current_question: str
    answer: str
    score: int
    reasons: str
    cycle_count: int
    history: List[Dict]
    evaluation: List[Dict]
    objective: str
    starting_string: str
    params: Dict
    session_id: str
